// Модель приложения: хранит дела и выполняет все операции над ними.
//
// Модель ничего не знает про FLTK и про кнопки. Благодаря этому её можно
// протестировать без графического интерфейса (см. tests/test_todo_list.cpp).
// -----------------------------------------------------------------------------

#pragma once

#include "TodoItem.h"

#include <cstddef>
#include <string>
#include <vector>

namespace todo {

/// Список дел с уникальными идентификаторами.
///
/// Класс следует принципу единственной ответственности: он отвечает только за
/// данные и их проверку. Как эти данные показать на экране, решает TodoWindow.
///
/// Ошибки сообщаются исключениями:
///   - std::invalid_argument — попытка добавить пустое дело;
///   - std::out_of_range     — попытка изменить или удалить несуществующее дело.
class TodoList {
public:
    /// Добавляет дело и возвращает его уникальный идентификатор.
    ///
    /// Пробелы, табы и переводы строк по краям названия удаляются. Если после
    /// этого строка пустая, выбрасывается std::invalid_argument.
    ItemId add(std::string title);

    /// Отмечает дело как выполненное.
    ///
    /// Повторный вызов для уже выполненного дела безопасен (идемпотентен):
    /// состояние просто остаётся прежним.
    /// @throws std::out_of_range если дела с таким id нет.
    void markDone(ItemId id);

    /// Удаляет дело из списка.
    /// @throws std::out_of_range если дела с таким id нет.
    void remove(ItemId id);

    /// Доступ только для чтения ко всем делам в порядке добавления.
    const std::vector<TodoItem>& items() const noexcept { return items_; }

    /// Количество дел в списке.
    std::size_t size() const noexcept { return items_.size(); }

    /// Количество выполненных дел.
    std::size_t doneCount() const noexcept;

private:
    /// Ищет дело по id и возвращает ссылку на него.
    /// @throws std::out_of_range если дело не найдено.
    TodoItem& findById(ItemId id);

    std::vector<TodoItem> items_;

    /// Следующий свободный номер. Начинаем с 1, чтобы 0 можно было считать
    /// «невалидным» значением по умолчанию.
    ItemId nextId_ = 1;
};

}  // namespace todo
