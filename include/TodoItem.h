// -----------------------------------------------------------------------------
// TodoItem.h
//
// Одно дело в TODO-листе. Структура намеренно максимально простая: это обычные
// данные (plain data), без поведения. Вся логика работы со списком находится в
// классе TodoList.
// -----------------------------------------------------------------------------

#pragma once

#include <cstdint>
#include <string>

namespace todo {

/// Уникальный идентификатор дела.
///
/// Идентификатор не переиспользуется: даже если дело удалили, его номер больше
/// никогда не встретится. Это защищает интерфейс от ситуации, когда нажатие на
/// старую галочку могло бы изменить уже другое дело.
using ItemId = std::uint64_t;

/// Описание одного дела.
struct TodoItem {
    /// Уникальный номер дела в пределах одного TodoList.
    ItemId id = 0;

    /// Текст дела (уже без лишних пробелов по краям).
    std::string title;

    /// Выполнено ли дело.
    bool done = false;
};

}  // namespace todo
